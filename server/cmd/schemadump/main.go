package main

// schemadump 从当前开发库导出 schema-only 的 goose 基线迁移。
//
//	go run ./cmd/schemadump > migrations/00001_baseline.sql
//
// 为什么从实际库导出而不是按 GORM 模型生成：仓库里还有 docs/migrations/ 下的
// 手工 SQL（唯一索引、列类型、回填），模型无法完整表达它们。基线必须反映
// 「已经执行完所有手工迁移」的真实 schema。
//
// 只读：仅执行 information_schema 查询与 SHOW CREATE TABLE。

import (
	"context"
	"database/sql"
	"fmt"
	"log"
	"os"
	"regexp"
	"strings"

	_ "github.com/go-sql-driver/mysql"

	"kindergarten-server/internal/config"
)

var autoIncrementRe = regexp.MustCompile(`\s+AUTO_INCREMENT=\d+`)

func main() {
	cfgPath := os.Getenv("CONFIG_PATH")
	if cfgPath == "" {
		cfgPath = "configs/app.ini"
	}
	cfg, err := config.Load(cfgPath)
	if err != nil {
		log.Fatal("load config:", err)
	}
	if cfg.MySQL.DSN == "" {
		log.Fatal("MySQL DSN 为空")
	}

	db, err := sql.Open("mysql", cfg.MySQL.DSN)
	if err != nil {
		log.Fatal("open:", err)
	}
	defer func() { _ = db.Close() }()
	ctx := context.Background()

	rows, err := db.QueryContext(ctx, `
		SELECT table_name
		FROM information_schema.tables
		WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE'
		ORDER BY table_name`)
	if err != nil {
		log.Fatal("list tables:", err)
	}
	var tables []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			log.Fatal("scan table:", err)
		}
		if name == "goose_db_version" {
			continue
		}
		tables = append(tables, name)
	}
	if err := rows.Err(); err != nil {
		log.Fatal("list tables:", err)
	}
	_ = rows.Close()

	if len(tables) == 0 {
		log.Fatal("当前数据库没有表，无法生成基线")
	}

	fmt.Println("-- Code generated by cmd/schemadump from the live development schema.")
	fmt.Println("-- Do not edit manually: every schema change must be a new goose migration.")
	fmt.Println("-- +goose NO TRANSACTION")
	fmt.Println()
	fmt.Println("-- +goose Up")
	fmt.Println("SET FOREIGN_KEY_CHECKS=0;")
	for _, table := range tables {
		var name, ddl string
		if err := db.QueryRowContext(ctx, "SHOW CREATE TABLE "+quoteIdent(table)).Scan(&name, &ddl); err != nil {
			log.Fatalf("show create table %s: %v", table, err)
		}
		// 去掉 AUTO_INCREMENT 当前值，避免把开发库的下一个自增 ID 带进基线。
		ddl = autoIncrementRe.ReplaceAllString(ddl, "")
		fmt.Printf("%s;\n", ddl)
	}
	fmt.Println("SET FOREIGN_KEY_CHECKS=1;")
	fmt.Println()
	fmt.Println("-- +goose Down")
	fmt.Println("-- baseline: down is intentionally empty; restore from a snapshot if needed.")
}

func quoteIdent(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}
