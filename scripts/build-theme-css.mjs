#!/usr/bin/env node
/**
 * Generate themes.css from shared-design-tokens/themes.json.
 *
 * bright is the default (base tokens.css). deep and ink are opt-in variants
 * scoped by `[data-theme]` on <html>.
 *
 * The renderer is exported so scripts/design-sync.mjs can compare the
 * committed copies without rewriting them during a read-only check.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const themesPath = path.join(repoRoot, 'shared-design-tokens', 'themes.json')

const sharedMap = {
  fg: '--fg',
  fg2: '--fg-2',
  muted: '--muted',
  hint: '--hint',
  onBrand: '--on-brand',
  onAccent: '--on-accent',
  border: '--border',
  success: '--success',
  successBg: '--success-wash',
  warning: '--warning',
  warningBg: '--warning-wash',
  danger: '--danger',
  dangerBg: '--danger-wash',
  info: '--info',
  infoBg: '--info-wash',
  star: '--star',
  starBg: '--star-wash',
  shadowSm: '--shadow-sm',
  shadowMd: '--shadow-md',
  shadowLg: '--shadow-lg',
}
const surfaceMap = {
  bg: '--bg',
  gradientPage: '--bg-gradient',
  surface: '--surface',
  surfaceWarm: '--surface-warm',
  primary: '--accent',
  primaryLight: '--accent-soft',
  primaryDark: '--accent-deep',
  primaryBg: '--accent-wash',
  gradientBrand: '--accent-gradient',
  gradientBrandSoft: '--accent-gradient-soft',
  sidebar: '--sidebar',
  sidebarHover: '--sidebar-hover',
}

export const THEME_OUTPUTS = [
  path.join(repoRoot, 'shared-design-tokens', 'build', 'css', 'themes.css'),
  path.join(repoRoot, 'docs', 'design-previews', '2026-10-25-full-redesign', '_shared', 'themes.css'),
  path.join(repoRoot, 'docs', 'design-previews', '2026-10-27-celestial-blue', '_shared', 'themes.css'),
  path.join(repoRoot, 'docs', 'design-previews', '2026-10-27-starry-blue', '_shared', 'themes.css'),
  path.join(repoRoot, 'docs', 'design-previews', '2026-10-27-petit-prince', '_shared', 'themes.css'),
]

export function renderThemesCss() {
  const themes = JSON.parse(fs.readFileSync(themesPath, 'utf8'))
  const lines = []
  lines.push('/* Generated by scripts/build-theme-css.mjs from shared-design-tokens/themes.json.')
  lines.push(' * Default (no data-theme) = bright. Variants: deep | ink | celestial | starry | petitprince.')
  lines.push(' * Load after tokens.css and before page styles.css.')
  lines.push(' */')
  lines.push('')

  for (const [name, theme] of Object.entries(themes)) {
    const shared = theme.shared || {}
    if (Object.keys(shared).length) {
      lines.push(`:root[data-theme="${name}"] {`)
      for (const [key, value] of Object.entries(shared)) {
        if (sharedMap[key]) lines.push(`  ${sharedMap[key]}: ${value};`)
      }
      lines.push('}')
      lines.push('')
    }
    for (const surface of ['teacher', 'parent', 'admin']) {
      const vars = theme[surface] || {}
      if (!Object.keys(vars).length) continue
      lines.push(`:root[data-theme="${name}"][data-surface="${surface}"] {`)
      for (const [key, value] of Object.entries(vars)) {
        if (surfaceMap[key]) lines.push(`  ${surfaceMap[key]}: ${value};`)
      }
      if (vars.brand) lines.push(`  --brand-${surface}: ${vars.brand};`)
      lines.push('}')
      lines.push('')
    }
  }
  return lines.join('\n')
}

export function writeThemesCss({ quiet = false } = {}) {
  const css = renderThemesCss()
  for (const out of THEME_OUTPUTS) {
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, css, 'utf8')
    if (!quiet) console.log(`[themes] wrote ${out}`)
  }
  return THEME_OUTPUTS.length
}

const invokedDirectly = process.argv[1] &&
  path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()

if (invokedDirectly) {
  writeThemesCss()
}
